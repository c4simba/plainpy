def text(n, seed):
    """Words from a small vocabulary, a pseudo-random sequence: compressible, matches at all distances."""
    words = [b"alpha", b"beta", b"gamma", b"delta", b"kolibri", b"nectar", b"plainpy", b"zlib", b"window", b"x"]
    out = bytearray()
    s = seed
    while len(out) < n:
        s = (s * 1103515245 + 12345) & 0x7FFFFFFF
        out += words[(s >> 16) % len(words)]
        out += b" \n"[(s >> 8) & 1:((s >> 8) & 1) + 1]
    return bytes(out[:n])

def far(n):
    """34 KB of text, then pieces of it again from almost 32 KB back: long distances."""
    out = bytearray(text(34000, 9))
    k = 0
    while len(out) < n:
        k += 1
        back = 32768 - (k * 977) % 3000
        start = len(out) - back
        out += out[start:start + 200 + k % 50]
    return bytes(out[:n])

